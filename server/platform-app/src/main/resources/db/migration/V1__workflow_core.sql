CREATE TABLE workflow_app (
    id VARCHAR(36) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    app_type VARCHAR(20) NOT NULL,
    draft_json TEXT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE workflow_run (
    id VARCHAR(36) PRIMARY KEY,
    app_id VARCHAR(36) NOT NULL,
    graph_json TEXT NOT NULL,
    inputs_json TEXT NOT NULL,
    status VARCHAR(20) NOT NULL,
    outputs_json TEXT,
    error TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    finished_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_run_app FOREIGN KEY (app_id) REFERENCES workflow_app(id)
);
CREATE INDEX idx_run_app ON workflow_run(app_id, created_at);

CREATE TABLE workflow_node_run (
    id VARCHAR(512) PRIMARY KEY,
    run_id VARCHAR(36) NOT NULL,
    node_id VARCHAR(255) NOT NULL,
    node_type VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    inputs_json TEXT,
    outputs_json TEXT,
    error TEXT,
    duration_millis BIGINT NOT NULL DEFAULT 0,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_node_run UNIQUE (run_id, node_id),
    CONSTRAINT fk_node_run_run FOREIGN KEY (run_id) REFERENCES workflow_run(id)
);
CREATE INDEX idx_node_run_run ON workflow_node_run(run_id, started_at);

CREATE TABLE workflow_run_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(36) NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    node_id VARCHAR(255),
    data_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_event_run FOREIGN KEY (run_id) REFERENCES workflow_run(id)
);
CREATE INDEX idx_event_run_sequence ON workflow_run_event(run_id, id);
